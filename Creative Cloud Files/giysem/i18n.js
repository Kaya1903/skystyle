// Turkish "de/da" (also) after a day name: "Dün de", "Salı da", "3 Kasım da".
function trDe(word) {
  const v = (String(word).match(/[aıouâeiöüAIOUEİÖÜ]/g) || ['e']).pop();
  return /[aıouâAIOU]/.test(v) ? ' da' : ' de';
}

// Russian plural: 1 день, 2 дня, 5 дней (11 to 14 always take the last form).
function ruPlural(n, one, few, many) {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

// Azerbaijani "da/də" (also) after a day name: "Dünən də", "Bazar da".
function azDe(word) {
  const v = (String(word).match(/[aıouəeiöüAIOUƏEİÖÜ]/g) || ['e']).pop();
  return /[aıouAIOU]/.test(v) ? ' da' : ' də';
}

